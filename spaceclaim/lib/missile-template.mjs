export function renderModelScript(apiVersion) {
  const version = apiVersion || "";
  // replaceAll matters: the placeholder appears in both the header comment and the versioned import.
  if (version) return MODEL_SCRIPT.replaceAll("__API_VERSION__", version);
  // Without a known version the versioned import would not parse; bind the name to None instead.
  return MODEL_SCRIPT
    .replace("from SpaceClaim.Api.__API_VERSION__ import WindowExportFormat", "WindowExportFormat = None  # target API version unknown")
    .replaceAll("__API_VERSION__", "");
}
